#!/usr/bin/env python3
"""Find authorization-check methods in Java sources and emit New Relic Java agent XML candidates.

The XML only *traces* the methods (they show up as segments/spans), it never captures arguments.
That makes "this API never ran an ownership check" visible at runtime, which backs up
code-review finding F4 without code changes. It cannot produce resource.owner_match.

Heuristics (regex based, no Java parser - review the report before using the XML):
  1. classes implementing PermissionEvaluator            -> hasPermission       (high)
  2. beans called from @PreAuthorize("@bean.method(..)") -> that method          (high)
  3. authz-like method names in authz-like classes       -> e.g. check*/verify* (medium)

Usage:
  python3 scripts/gen_xml_candidates.py <src-dir> --xml out/authz-extension.xml --report out/xml-candidates.md
"""
from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path
from xml.sax.saxutils import escape

PACKAGE = re.compile(r"^\s*package\s+([\w.]+)\s*;", re.M)
TYPE_DECL = re.compile(r"^(?:public\s+|final\s+|abstract\s+)*(class|interface|record|enum)\s+(\w+)([^{]*)\{", re.M)
BEAN_NAME = re.compile(r"@(?:Component|Service|Repository|Controller|RestController)\s*\(\s*(?:value\s*=\s*)?\"(\w+)\"")
METHOD = re.compile(r"^\s*(?:@\w+(?:\([^)]*\))?\s*)*(public|protected)\s+(?:static\s+|final\s+|synchronized\s+)*"
                    r"[\w<>\[\], ?.]+\s+(\w+)\s*\(", re.M)
PREAUTH_BEAN_CALL = re.compile(r"@PreAuthorize\(\s*\"[^\"]*?@(\w+)\.(\w+)\s*\(")
AUTHZ_CLASS = re.compile(r"(Security|Authoriz|Permission|Access|Ownership|Owner|Guard|Policy|Acl)", re.I)
AUTHZ_METHOD = re.compile(r"^(check|verify|assert|authorize|ensure|require|can[A-Z]|has[A-Z]|is(Owner|Allowed|Permitted|Authorized))")
SKIP_ANNOTATION = re.compile(r"@(?:[\w.]+\.)?CheckOwnership\b")


@dataclass(frozen=True)
class Candidate:
    class_name: str
    method: str
    file: str
    line: int
    reason: str
    confidence: str


@dataclass
class JavaType:
    fqcn: str
    simple: str
    bean_names: set
    header: str
    file: Path
    text: str


def parse(path: Path, root: Path) -> JavaType | None:
    text = path.read_text(encoding="utf-8", errors="replace")
    decl = TYPE_DECL.search(text)
    if not decl or decl.group(1) not in ("class", "record"):
        return None
    pkg = PACKAGE.search(text)
    simple = decl.group(2)
    fqcn = f"{pkg.group(1)}.{simple}" if pkg else simple
    beans = set(BEAN_NAME.findall(text)) | {simple[0].lower() + simple[1:]}
    return JavaType(fqcn, simple, beans, decl.group(3), path.relative_to(root), text)


def line_of(text: str, index: int) -> int:
    return text.count("\n", 0, index) + 1


def declaration_head(text: str, name_index: int) -> str:
    """Text of one member declaration up to its name: from the previous ';' / '{' / '}' on."""
    start = max(text.rfind(ch, 0, name_index) for ch in ";{}") + 1
    return text[start:name_index]


def methods(t: JavaType):
    for m in METHOD.finditer(t.text):
        yield m.group(2), line_of(t.text, m.start(2)), m


def find_candidates(src: Path) -> list[Candidate]:
    types = [t for p in sorted(src.rglob("*.java")) if (t := parse(p, src))]
    by_bean = {b: t for t in types for b in t.bean_names}
    found: dict[tuple[str, str], Candidate] = {}

    def add(c: Candidate):
        key = (c.class_name, c.method)
        rank = {"high": 0, "medium": 1}
        if key not in found or rank[c.confidence] < rank[found[key].confidence]:
            found[key] = c

    for t in types:
        if "PermissionEvaluator" in t.header:
            for name, line, _ in methods(t):
                if name == "hasPermission":
                    add(Candidate(t.fqcn, name, str(t.file), line, "implements PermissionEvaluator", "high"))
        for bean, method in PREAUTH_BEAN_CALL.findall(t.text):
            target = by_bean.get(bean)
            if target:
                line = next((ln for n, ln, _ in methods(target) if n == method), 1)
                add(Candidate(target.fqcn, method, str(target.file), line,
                              f"called from @PreAuthorize in {t.simple}", "high"))
        if AUTHZ_CLASS.search(t.simple):
            for name, line, m in methods(t):
                if AUTHZ_METHOD.match(name) and not SKIP_ANNOTATION.search(declaration_head(t.text, m.start(2))):
                    add(Candidate(t.fqcn, name, str(t.file), line, "authorization-like name", "medium"))
    return sorted(found.values(), key=lambda c: (c.confidence != "high", c.class_name, c.method))


def to_xml(candidates: list[Candidate]) -> str:
    by_class: dict[str, list[Candidate]] = {}
    for c in candidates:
        by_class.setdefault(c.class_name, []).append(c)
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- Generated by scripts/gen_xml_candidates.py. Review xml-candidates.md before use.",
           "     Traces authorization checks only; no arguments are captured. -->",
           '<extension xmlns="https://newrelic.com/docs/java/xsd/v1.0"',
           '           xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
           '           xsi:schemaLocation="newrelic-extension extension.xsd"',
           '           name="authz-radar-checks" version="1.0">',
           '  <instrumentation metricPrefix="AuthzCheck">']
    for cls, items in by_class.items():
        out += ['    <pointcut transactionStartPoint="false">', f"      <className>{escape(cls)}</className>"]
        for c in sorted({i.method for i in items}):
            out += ["      <method>", f"        <name>{escape(c)}</name>", "      </method>"]
        out.append("    </pointcut>")
    out += ["  </instrumentation>", "</extension>", ""]
    return "\n".join(out)


def to_report(candidates: list[Candidate]) -> str:
    out = ["# XML 計装の候補", "",
           "認可チェックらしいメソッドを、ソースコードから正規表現で探した結果。**XML を使う前に確認すること。**", "",
           "- XML はメソッドの実行を Span として記録するだけで、引数は記録しない。",
           "- これで「その API で認可チェックが一度も実行されていない」ことが実行時に見える（コード監査 F4 の裏付け）。",
           "- `resource.owner_match` は作れない（値の比較にはコードが必要）。", "",
           "| 確度 | クラス | メソッド | 場所 | 理由 |", "|---|---|---|---|---|"]
    out += [f"| {c.confidence} | `{c.class_name}` | `{c.method}` | `{c.file}:{c.line}` | {c.reason} |" for c in candidates]
    if not candidates:
        out.append("| — | 見つからなかった | — | — | 認可チェックが別の形で実装されているか、存在しない可能性がある |")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src")
    ap.add_argument("--xml", required=True)
    ap.add_argument("--report", required=True)
    args = ap.parse_args()
    candidates = find_candidates(Path(args.src))
    for target, content in ((args.xml, to_xml(candidates)), (args.report, to_report(candidates))):
        Path(target).parent.mkdir(parents=True, exist_ok=True)
        Path(target).write_text(content, encoding="utf-8")
    print(f"{len(candidates)} candidates ({sum(c.confidence == 'high' for c in candidates)} high)")


if __name__ == "__main__":
    main()
