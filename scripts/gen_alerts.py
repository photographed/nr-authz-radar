#!/usr/bin/env python3
"""Generate New Relic alert conditions (Terraform) for the current stage and data sources.

Routing follows the evidence level of each detection (shared/detections.json):
  evidence -> CRITICAL (pages, and may trigger Autopilot)
  strong   -> HIGH only (quiet channel, no Autopilot; muted while learning_mode = true)
  anomaly  -> not generated by default; --include-anomaly puts them in a separate policy
              with no notifications (review them in a digest, never page on them)

Only alerts that can work with what the account has today are generated. The rest are listed
in SKIPPED.md with what would enable them, so reports keep "what works now" and
"recommendations" apart (shared/goals.md).

Usage:
  python3 scripts/gen_alerts.py --stage S2 --sources spans,browser_dt --out out/terraform [--include-anomaly] [--lang en]
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "shared" / "alerts.json"
DETECTIONS = ROOT / "shared" / "detections.json"
STATIC = ROOT / "templates" / "terraform"
STAGES = ["S0", "S1", "S2", "S3"]
SOURCES = {"spans": "分散トレーシング（Span）", "browser_dt": "Browser + 分散トレーシング",
           "deployments": "Change Tracking（デプロイ記録）", "logs": "Logs"}
SOURCES_EN = {"spans": "distributed tracing (spans)", "browser_dt": "Browser + distributed tracing",
              "deployments": "change tracking (deployments)", "logs": "Logs"}
TEXT = {
    "ja": {"title": "# 生成しなかったアラート（現在の段階: {stage}）",
           "rec": "## 推奨: これを満たすと追加できるアラート",
           "head": "| 検知 | 名前 | 証拠の強さ | 必要なこと |", "none": "| — | — | — | なし |",
           "anomaly": "## 異常の検知（既定では通知しない）",
           "anomaly_note": "量や割合の変化は偽陽性が多いため、既定では生成しない。`--include-anomaly` で、通知しない別のポリシーに入れて日次で確認できる。",
           "hunt": "## アラートにしない検知（Hunt で確認する）", "hunt_head": "| 検知 | 理由 |",
           "stage": "段階 {need} が必要（現在 {stage}）", "source": "データソースが必要: ",
           "anomaly_reason": "異常の検知（通知しない。`--include-anomaly` で日次確認用のポリシーに追加）"},
    "en": {"title": "# Alerts not generated (current stage: {stage})",
           "rec": "## Recommendations: alerts you can add once these are in place",
           "head": "| Detection | Name | Evidence level | Needs |", "none": "| — | — | — | none |",
           "anomaly": "## Anomaly detections (not notified by default)",
           "anomaly_note": "Changes in volume or ratio produce many false positives, so they are not generated by default. `--include-anomaly` adds them to a separate policy with no notifications, for a daily review.",
           "hunt": "## Detections that are not alerts (run them in Hunt)", "hunt_head": "| Detection | Why |",
           "stage": "stage {need} (now {stage})", "source": "data source: ",
           "anomaly_reason": "anomaly (not notified; `--include-anomaly` adds it to the digest policy)"},
}
HUNT_ONLY_EN = {
    "D05": "needs stage S3 attributes and thresholds differ widely between organizations",
    "D08": "needs a comparison with the normal period (COMPARE WITH), which alerts cannot do",
    "D09": "looks at the shape of a distribution (two peaks), not a simple threshold",
    "D13": "uses a nested query, likely unsupported in alert conditions",
    "D14": "needs a comparison with the normal period",
    "D15": "a configuration risk, not an attack signal (better in a periodic report)",
    "D17": "needs 'first seen' (earliest), which alerts cannot do",
    "D18": "a reference query for correlation",
    "D20": "needs 'first seen destination' (earliest); run it in Hunt when D21 fires",
}
PLACEHOLDERS = {"{appName}": "${var.app_name}", "{bypassScopePattern}": "${var.bypass_scope_pattern}"}
PAGING_LEVELS = ("evidence", "strong")


def load() -> tuple[dict, dict]:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    detections = json.loads(DETECTIONS.read_text(encoding="utf-8"))
    for a in catalog["alerts"]:
        a["evidence"] = detections["detections"][a["id"]]["evidence"]
    return catalog, detections


def hcl_string(text: str) -> str:
    """Quote a literal for HCL: escape quotes/backslashes and template sequences (${ and %{)."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("${", "$${").replace("%{", "%%{")
    return f'"{escaped}"'


def nrql_expression(nrql: str) -> str:
    quoted = hcl_string(nrql)
    for placeholder, ref in PLACEHOLDERS.items():
        quoted = quoted.replace(placeholder, ref)
    return quoted


def threshold_block(kind: str, t: dict, window: int) -> str:
    return (f"  {kind} {{\n"
            f"    operator              = \"{t['operator']}\"\n"
            f"    threshold             = {t['threshold']}\n"
            f"    threshold_duration    = {window}\n"
            f"    threshold_occurrences = \"at_least_once\"\n"
            f"  }}\n")


def thresholds(alert: dict) -> list[tuple[str, dict]]:
    """evidence keeps critical (+warning); strong and anomaly become warning-only (HIGH)."""
    if alert["evidence"] == "evidence":
        return [(k, alert[k]) for k in ("critical", "warning") if k in alert]
    if alert["evidence"] == "strong":
        return [("warning", alert.get("critical") or alert["warning"])]
    return [("warning", alert.get("warning") or alert["critical"])]


def condition(alert: dict) -> str:
    rid = alert["id"].lower()
    window = alert["window_seconds"]
    policy = "authz_radar_anomaly" if alert["evidence"] == "anomaly" else "authz_radar"
    lines = [
        f'resource "newrelic_nrql_alert_condition" "{rid}" {{',
        "  account_id                   = var.account_id",
        f"  policy_id                    = newrelic_alert_policy.{policy}.id",
        f'  type                         = "{alert["type"]}"',
        f'  name                         = {hcl_string("[authz-radar] " + alert["id"] + " " + alert["name"])}',
        f'  description                  = {hcl_string("nr-authz-radar " + alert["id"] + " / stage " + alert["stage"] + " / " + alert["evidence"])}',
        f'  runbook_url                  = "${{var.runbook_base_url}}/{alert["runbook"]}"',
        "  enabled                      = true",
        "  violation_time_limit_seconds = 86400",
        f"  aggregation_window           = {window}",
        '  aggregation_method           = "event_flow"',
        "  aggregation_delay            = 120",
    ]
    if alert["type"] == "baseline":
        lines.append('  baseline_direction           = "upper_only"')
    lines += ["", "  nrql {", f"    query = {nrql_expression(alert['nrql'])}", "  }", ""]
    body = "\n".join(lines) + "\n"
    for kind, t in thresholds(alert):
        body += threshold_block(kind, t, window)
    return body + "}\n"


ANOMALY_POLICY = '''# Anomaly detections: no workflow points at this policy, so nothing is notified.
# Review its issues in a daily digest; do not page on volume or ratio changes.
resource "newrelic_alert_policy" "authz_radar_anomaly" {
  name                = "[authz-radar] ${var.app_name} anomaly (digest)"
  incident_preference = "PER_CONDITION_AND_TARGET"
}
'''


def select(alerts: list[dict], stage: str, sources: set[str], lang: str = "ja",
           include_anomaly: bool = False) -> tuple[list[dict], list[tuple[dict, str]]]:
    t, names, sep = TEXT[lang], (SOURCES if lang == "ja" else SOURCES_EN), ("、" if lang == "ja" else ", ")
    chosen, skipped = [], []
    for a in alerts:
        if STAGES.index(a["stage"]) > STAGES.index(stage):
            skipped.append((a, t["stage"].format(need=a["stage"], stage=stage)))
        elif missing := [s for s in a["requires"] if s not in sources]:
            skipped.append((a, t["source"] + sep.join(names[s] for s in missing)))
        elif a["evidence"] not in PAGING_LEVELS and not include_anomaly:
            skipped.append((a, t["anomaly_reason"]))
        else:
            chosen.append(a)
    return chosen, skipped


def skipped_report(skipped: list[tuple[dict, str]], hunt_only: dict, detections: dict, stage: str,
                   lang: str = "ja") -> str:
    t = TEXT[lang]
    levels = detections["levels"]
    name = (lambda a: a["name"]) if lang == "ja" else (lambda a: a.get("name_en", a["name"]))
    level = lambda a: levels[a["evidence"]]["ja" if lang == "ja" else "en"]  # noqa: E731
    rec = [(a, why) for a, why in skipped if why != t["anomaly_reason"]]
    anomalies = [a for a, why in skipped if why == t["anomaly_reason"]]
    out = [t["title"].format(stage=stage), "", t["rec"], "", t["head"], "|---|---|---|---|"]
    out += [f"| {a['id']} | {name(a)} | {level(a)} | {why} |" for a, why in rec] or [t["none"]]
    if anomalies:
        out += ["", t["anomaly"], "", t["anomaly_note"], ""]
        out += [f"- {a['id']} {name(a)}" for a in anomalies]
    out += ["", t["hunt"], "", t["hunt_head"], "|---|---|"]
    out += [f"| {k} | {v if lang == 'ja' else HUNT_ONLY_EN.get(k, v)} |" for k, v in hunt_only.items()]
    return "\n".join(out) + "\n"


def generate(stage: str, sources: set[str], out: Path, lang: str = "ja",
             include_anomaly: bool = False) -> tuple[list[dict], list[tuple[dict, str]]]:
    catalog, detections = load()
    chosen, skipped = select(catalog["alerts"], stage, sources, lang, include_anomaly)
    out.mkdir(parents=True, exist_ok=True)
    for f in STATIC.glob("*.tf"):
        shutil.copy(f, out / f.name)
    flags = f"--stage {stage} --sources {','.join(sorted(sources)) or '-'}" + (" --include-anomaly" if include_anomaly else "")
    header = (f"# Generated by scripts/gen_alerts.py {flags}\n"
              "# Do not edit by hand: change shared/alerts.json or shared/detections.json and regenerate.\n\n")
    body = "\n".join(condition(a) for a in chosen)
    if any(a["evidence"] == "anomaly" for a in chosen):
        body = ANOMALY_POLICY + "\n" + body
    (out / "alerts.tf").write_text(header + body, encoding="utf-8")
    (out / "SKIPPED.md").write_text(skipped_report(skipped, catalog["hunt_only"], detections, stage, lang),
                                    encoding="utf-8")
    return chosen, skipped


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", choices=STAGES, required=True)
    ap.add_argument("--sources", default="", help="comma separated: " + ", ".join(SOURCES))
    ap.add_argument("--out", required=True)
    ap.add_argument("--include-anomaly", action="store_true",
                    help="also generate anomaly detections, in a separate policy with no notifications")
    ap.add_argument("--lang", choices=["ja", "en"], default="ja", help="language of SKIPPED.md")
    args = ap.parse_args()
    sources = {s for s in args.sources.split(",") if s}
    unknown = sources - set(SOURCES)
    if unknown:
        ap.error(f"unknown sources: {', '.join(sorted(unknown))}")
    chosen, skipped = generate(args.stage, sources, Path(args.out), args.lang, args.include_anomaly)
    counts = {lv: sum(a["evidence"] == lv for a in chosen) for lv in ("evidence", "strong", "anomaly")}
    print(f"generated {len(chosen)} alert conditions ({counts['evidence']} critical, {counts['strong']} high, "
          f"{counts['anomaly']} digest), skipped {len(skipped)} (see SKIPPED.md)")


if __name__ == "__main__":
    main()
